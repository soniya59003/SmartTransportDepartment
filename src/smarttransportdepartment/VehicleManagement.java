    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
try {
    String vehicleNo = txtVehicleNumber.getText();

    String sql = "SELECT * FROM vehicle WHERE vehicle_number = ?";

    java.sql.Connection con = DBConnection.getConnection();

    java.sql.PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, vehicleNo);

    java.sql.ResultSet rs = pst.executeQuery();

    if (rs.next()) {
        txtOwnerName.setText(rs.getString("owner_name"));
        txtVehicleType.setText(rs.getString("vehicle_type"));

        javax.swing.JOptionPane.showMessageDialog(
            this, "Vehicle Found!"
        );
    } else {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Vehicle Not Found!"
        );
    }

    rs.close();
    pst.close();
    con.close();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, e.getMessage()
    );
}    }//GEN-LAST:event_jButton4ActionPerformed

