    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
java.sql.Connection con = DBConnection.getConnection();

String sql = "UPDATE vehicle SET owner_name = ?, vehicle_type = ? WHERE vehicle_number = ?";
java.sql.PreparedStatement pst = con.prepareStatement(sql);

pst.setString(1, txtOwnerName.getText());
pst.setString(2, txtVehicleType.getText());
pst.setString(3, txtVehicleNumber.getText());

int rows = pst.executeUpdate();

if (rows > 0) {
    javax.swing.JOptionPane.showMessageDialog(this, "Vehicle Updated Successfully!");
} else {
    javax.swing.JOptionPane.showMessageDialog(this, "Vehicle Not Found!");
}

pst.close();
con.close();

} catch (Exception e) {
javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
int confirm = javax.swing.JOptionPane.showConfirmDialog(
this,
"Are you sure you want to delete this vehicle?",
"Confirm Delete",
javax.swing.JOptionPane.YES_NO_OPTION
);

if (confirm == javax.swing.JOptionPane.YES_OPTION) {

    java.sql.Connection con = DBConnection.getConnection();

    if (con == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Database connection failed!");
        return;
    }

    String sql = "DELETE FROM vehicle WHERE vehicle_number = ?";
    java.sql.PreparedStatement pst = con.prepareStatement(sql);

    pst.setString(1, txtVehicleNumber.getText());

    int rows = pst.executeUpdate();

    if (rows > 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Vehicle Deleted Successfully!");

        txtVehicleNumber.setText("");
        txtOwnerName.setText("");
        txtVehicleType.setText("");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Vehicle Not Found!");
    }

    pst.close();
    con.close();
}

} catch (Exception e) {
javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
}
    }//GEN-LAST:event_jButton3ActionPerformed

